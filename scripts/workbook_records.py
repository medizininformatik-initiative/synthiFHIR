def record(sheet, values=None):
    values = {} if values is None else values
    if not isinstance(values, Mapping):
        raise TypeError('Workbook rows must use named fields')
    unknown = values.keys() - SCHEMAS[sheet]
    if unknown:
        raise ValueError(f'Unknown {sheet} fields: {sorted(unknown)}')
    return {field: values.get(field, '') for field in SCHEMAS[sheet]}


def ordered_values(sheet, row, headers):
    """Serialize by actual header names, never by dictionary insertion order."""
    if len(headers) != len(set(headers)) or set(headers) != set(SCHEMAS[sheet]):
        raise ValueError(f'Workbook headers do not match {sheet} fields')
    normalized = record(sheet, row)
    return [normalized[field] for field in headers]
